// Playwright CLI run-code. Requires an authenticated independent 3100 browser.
// Browser fixtures block workspace reset and financial writes; never use a production session.
async page => {
 await page.route('**/api/v1/wealth/workspace/reset',route=>route.fulfill({status:200,contentType:'application/json',body:'{}'}));
 const checks=[]; const check=(condition,label)=>{if(!condition)throw new Error(label);checks.push(label);};
 const errors=[]; page.on('pageerror',error=>errors.push(error.message));
 await page.setViewportSize({width:1440,height:1000});
 await page.reload();
 const input=page.getByRole('textbox',{name:'向 NOVA 提问'});
 await input.waitFor(); await input.fill('未发送草稿：稍后查询账单');
 const traffic=[];const observe=request=>{if(/nova|conversations|workspace\/reset/.test(request.url()))traffic.push(request.method()+' '+new URL(request.url()).pathname);};
 page.on('request',observe);
 const panel=await page.locator('#nova-panel').elementHandle();const inputNode=await input.elementHandle();
 const before=await page.locator('#nova-toggle').boundingBox();
 await page.getByRole('button',{name:'查看财务概要·收起对话',exact:true}).click();
 await page.getByRole('heading',{name:'账户与卡片',exact:true}).waitFor();
 const after=await page.locator('#nova-toggle').boundingBox();
 check(JSON.stringify(before)===JSON.stringify(after),'模式按钮位置和宽度一致');
 check(await input.inputValue()==='未发送草稿：稍后查询账单','大屏到侧栏保留输入');
 check(await panel.evaluate(node=>node===document.querySelector('#nova-panel')),'侧栏保留同一个NOVA DOM实例');
 check(await inputNode.evaluate(node=>node===document.querySelector('.agent-compose input')),'侧栏保留同一个输入节点');
 const dimensions=await page.locator('#nova-panel').evaluate(node=>{const r=node.getBoundingClientRect();const s=getComputedStyle(node);return {right:r.right,top:r.top,height:r.height,width:r.width,radius:s.borderTopLeftRadius};});
 check(dimensions.right===1440&&dimensions.top===0&&dimensions.height===1000&&dimensions.width>=390&&dimensions.radius==='20px','侧栏全高贴右且左侧圆角');
 const columns=await page.locator('.financial-overview').evaluate(node=>getComputedStyle(node).gridTemplateColumns.split(' '));
 check(columns.length===2&&columns[0]===columns[1],'概要等宽两列');
 check(await page.locator('.asset-summary-metrics').evaluate(node=>getComputedStyle(node).gridTemplateColumns.split(' ').length===2),'资产明细两列');
 check(await page.getByRole('button',{name:'＋ 新建/历史对话',exact:true}).count()===1,'只有一个新建历史入口');
 await input.fill(''); await input.evaluate(node=>node.blur()); await page.waitForFunction(()=>document.getAnimations().every(animation=>animation.playState!=='running')); await page.screenshot({path:'output/playwright/home22-docked-1440.png'});
 await page.getByRole('button',{name:'展开NOVA，返回大屏',exact:true}).click();
 await page.locator('.home-workspace.nova-expanded').waitFor();
 check(await panel.evaluate(node=>node===document.querySelector('#nova-panel')),'回大屏仍同一NOVA节点');
 check(!await page.getByRole('heading',{name:'账户与卡片',exact:true}).isVisible(),'大屏隐藏业务卡');
 check(traffic.length===0,'两次模式切换不请求会话或重置轮次');
 page.off('request',observe);
 await page.waitForFunction(()=>document.getAnimations().every(animation=>animation.playState!=='running')); await page.screenshot({path:'output/playwright/home22-expanded-1440.png'});
 await page.getByRole('button',{name:'＋ 新建/历史对话',exact:true}).click();
 check(await page.getByRole('navigation',{name:'NOVA 对话历史'}).isVisible(),'大屏历史菜单可达');
 await page.getByRole('button',{name:'＋ 新建/历史对话',exact:true}).click();
 await page.getByRole('navigation',{name:'主要功能'}).getByRole('button',{name:'账单洞察'}).click();
 await page.getByRole('heading',{name:'查看支出与变化'}).waitFor();
 await page.getByRole('heading',{name:'查看支出与变化'}).waitFor();checks.push('账单原入口保留');
 await page.getByRole('navigation',{name:'主要功能'}).getByRole('button',{name:'转账与收款'}).click();
 await page.getByRole('heading',{name:'创建转账任务'}).waitFor();checks.push('转账原页面可达');
 await page.getByRole('navigation',{name:'主要功能'}).getByRole('button',{name:'卡片',exact:false}).click();
 await page.locator('.card-management').waitFor();checks.push('卡片管理原页面可达');
 await page.getByRole('navigation',{name:'主要功能'}).getByRole('button',{name:'订阅'}).click();
 await page.getByRole('heading',{name:'管理订阅',exact:true}).waitFor();checks.push('订阅原页面可达');
 await page.getByRole('navigation',{name:'主要功能'}).getByRole('button',{name:'概览'}).click();
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.getByRole('button',{name:'展开NOVA，返回大屏',exact:true}).click();
 await page.locator('.home-workspace.nova-expanded').waitFor();
 check(await page.locator('.nova-expanded').count()===1,'减少动画模式仍可切换');
 check(await page.locator('#nova-panel').evaluate(node=>getComputedStyle(node).animationName==='none'),'减少动画禁用面板动画');
 await page.waitForFunction(()=>document.getAnimations().every(animation=>animation.playState!=='running')); await page.screenshot({path:'output/playwright/home22-reduced-motion.png'});
 await page.emulateMedia({reducedMotion:'no-preference'});
 await page.setViewportSize({width:390,height:844});
 check(await page.locator('body').evaluate(()=>document.documentElement.scrollWidth<=390),'390px无横向溢出');
 check(await input.isVisible(),'窄屏输入可达');
 await page.waitForFunction(()=>document.getAnimations().every(animation=>animation.playState!=='running')); await page.screenshot({path:'output/playwright/home22-mobile-smoke.png'});
 await page.reload();
 check(await page.locator('#nova-panel').count()===0,'首次窄屏保持原业务优先布局');
 await page.locator('#nova-toggle').click();await input.waitFor();
 const mobileInput=await input.boundingBox();check(mobileInput.y+mobileInput.height<=844-68,'首次窄屏打开后输入不被底部导航遮挡');
 await page.screenshot({path:'output/playwright/home22-mobile-first-use.png'});
 await page.setViewportSize({width:1440,height:1000});
 check(await page.locator('.nova-home-suggestions button:visible').count()===4,'大屏保留四个已确认建议入口');
 const sends=[];const observeSend=request=>{if(request.url().endsWith('/nova/chat/stream'))sends.push(request.url());};page.on('request',observeSend);
 await page.locator('.nova-home-suggestions button').first().click();
 check(await input.inputValue()==='帮我看看最近的支出'&&sends.length===0,'建议只填入可编辑输入，不自动提交');page.off('request',observeSend);
 await input.fill('');await input.evaluate(node=>node.blur());
 await page.waitForFunction(()=>document.getAnimations().every(animation=>animation.playState!=='running'));
 await page.screenshot({path:'output/playwright/home22-expanded-1440.png'});
 check(errors.length===0,'无未捕获页面异常');
 return {checks,errors,dimensions};
}
